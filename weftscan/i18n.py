#: Engine fingerprints and the label shown for each.
DEVICE_TYPE_KEYS: dict[str, str] = {
 'Router': 'type.router',
 'Windows PC': 'type.windows',
 'Linux Server': 'type.linux',
 'Printer': 'type.printer',
 'IoT Device': 'type.iot',
 'Apple Device': 'type.apple',
 'Raspberry Pi': 'type.raspberry',
 'IP Camera': 'type.camera',
 'Server': 'type.server',
 'Network Device': 'type.netdev',
 'Mobile / Tablet': 'type.mobile',
 'Mac / Apple': 'type.apple'}

#: Short severity labels used in the findings table.
SEVERITY_KEYS: dict[str, str] = {'critical': 'sev.critical',
 'high': 'sev.high',
 'medium': 'sev.medium',
 'low': 'sev.low',
 'info': 'sev.info'}


def t(key: str, **kwargs: object) -> str:
    """Text for a catalogue key, with ``{placeholders}`` filled in.

    An unknown key is returned as-is, so a missing entry shows up in the UI
    instead of raising.
    """
    text = CATALOG.get(key, key)
    if not kwargs:
        return text
    try:
        return text.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return text


def device_type_label(device_type: str) -> str:
    """Display label of an engine device type."""
    key = DEVICE_TYPE_KEYS.get(device_type)
    if key:
        return t(key)
    if device_type in ("Unknown", ""):
        return t("value.unknown")
    return device_type


def severity_label(severity: str) -> str:
    """Short severity badge."""
    key = SEVERITY_KEYS.get(severity)
    return t(key) if key else severity.upper()


